"""Collect every stimuli/*/spec.json into questions.json + questions.csv and pack the Colab bundle.

python3.12 common/collect.py            # after all make.py ran
python3.12 common/collect.py --rebuild  # run every make.py first
"""
import csv
import json
import re
import subprocess
import sys
import zipfile
from collections import Counter
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

sys.path.insert(0, str(Path(__file__).resolve().parent))
from answers import DOWN, UP  # noqa: E402
from lib import CONDS, IMAGES, LANGS, ROOT, name, validate  # noqa: E402

MORE = re.compile(r"\b(more|higher|above|full|beat|went up|go up)\b")
LESS = re.compile(r"\b(fewer|less|lower|below|empty|worse|cleaner|went down|go down)\b")


def cue_px(sid):
    """Median height (px at 896) of the cue labels that differ between consistent and conflict (en).

    Changed pixels are merged horizontally into one blob per label (a partly overlapping digit pair would otherwise
    count as a fragment); each label's height is the vertical extent of its changed pixels."""
    a = np.asarray(Image.open(IMAGES / f"{name(sid, 'consistent', 'en')}.png").convert("RGB")).astype(int)
    b = np.asarray(Image.open(IMAGES / f"{name(sid, 'conflict', 'en')}.png").convert("RGB")).astype(int)
    changed = np.abs(a - b).max(axis=2) > 24
    blobs, _ = ndimage.label(ndimage.binary_dilation(changed, structure=np.ones((3, 15), bool)))
    hs = []
    for sl in ndimage.find_objects(blobs):
        rows = np.where(changed[sl].any(axis=1))[0]
        if len(rows) and changed[sl].sum() >= 20:          # ignore anti-aliasing specks
            hs.append(int(rows[-1] - rows[0] + 1))
    return int(np.median(hs)) if hs else 0


def answer_type(q):
    v = q["visual"]["en"][0].lower()
    if v in ("yes", "no"):
        return "yesno"
    if q["kind"] in ("read_value", "count") or re.fullmatch(r"[-\d.,:%h m]+", v):
        return "number"
    if v in UP["en"] or v in DOWN["en"]:
        return "direction"
    return "judgement" if q["kind"] == "relation" else "name"


def pair_more_is_yes(spec):
    """pair id -> True if the drawing answers 'yes' to the more/higher/above wording of that pair."""
    out = {}
    for q in spec["questions"]:
        p = q["prompt"]["en"]
        if q.get("pair") and MORE.search(p) and not LESS.search(p):
            out[q["pair"]] = q["visual"]["en"][0] == "yes"
    return out


def _a(q, side):
    """Canonical answer 'en · tr' for a table cell."""
    en, tr = q[side]["en"][0], q[side]["tr"][0]
    return en if en.lower() == tr.lower() else f"{en} · {tr}"


def write_questions_md(specs):
    """QUESTIONS.md: every sheet with its questions (en + tr) and the expected answer in each version."""
    out = ["# Questions per sheet", "",
           "Generated by `common/collect.py` from `stimuli/*/spec.json` (the source of truth; DESIGN.md is the original plan).", "",
           "Each sheet: columns consistent · conflict · no numbers, rows en · tr. Answers are written `en · tr` "
           "(one value when both languages agree). Prompts go to the model with the prefix `answer en ` / `answer tr `.", "",
           "- **from the drawing**: the answer when the marks are read. It is the expected answer on the consistent and no-numbers "
           "versions, and the *visual* answer on the conflict version.",
           "- **conflict: from the text**: the answer when the printed numbers of the conflict version are read. For `axis` and "
           "`legend` charts this is the correct answer; for `label` and `readout` charts there is no correct answer.",
           "- **no numbers**: ✓ = also asked on the no-numbers version; — = can't be answered from the drawing alone, not asked there.", ""]
    for s in specs:
        truth = "text is the correct answer" if s["conflict_has_truth"] else "no correct answer, only a preference"
        nq = len(s["questions"])
        out += [f"## {s['id'].split('_')[0]} · {s['title']['en']}", "",
                f"*{s['style']} · {s['chart']} · mechanism `{s['mechanism']}` (conflict: {truth}) · {nq} questions*", "",
                f"![{s['id']}](sheets/{s['id']}.png)", "",
                f"**Conflict:** {s['conflict_summary']}", "",
                "| # | question (en) | soru (tr) | from the drawing | conflict: from the text | no numbers |",
                "|---|---|---|---|---|:-:|"]
        for q in s["questions"]:
            en = q["prompt"]["en"].removeprefix("answer en ")
            tr = q["prompt"]["tr"].removeprefix("answer tr ")
            vis, txt = _a(q, "visual"), _a(q, "text")
            pair = f" *(pair {q['pair'].split('_')[-1]})*" if q.get("pair") else ""
            out.append(f"| {q['qid'].split('_', 1)[1]} | {en}{pair} | {tr} | {vis} | **{txt}** | {'✓' if q['nonumbers'] else '—'} |")
        out.append("")
    (ROOT / "QUESTIONS.md").write_text("\n".join(out), encoding="utf-8")


def main():
    makes = sorted((ROOT / "stimuli").glob("s*/make.py"))
    if "--rebuild" in sys.argv:
        for m in makes:
            subprocess.run([sys.executable, str(m)], check=True, cwd=ROOT)

    specs = []
    for m in makes:
        spec = json.loads((m.parent / "spec.json").read_text(encoding="utf-8"))
        validate(spec)
        specs.append(spec)

    rows = []
    for s in specs:
        px, more_yes = cue_px(s["id"]), pair_more_is_yes(s)
        for cond in CONDS:
            for lang in LANGS:
                for q in s["questions"]:
                    if cond == "nonumbers" and not q["nonumbers"]:
                        continue                                  # can't be answered from the drawing alone
                    rows.append({
                        "image": f"{name(s['id'], cond, lang)}.png", "stimulus": s["id"], "chart": s["chart"],
                        "style": s["style"], "mechanism": s["mechanism"], "conflict_has_truth": s["conflict_has_truth"],
                        "cond": cond, "lang": lang, "qid": q["qid"], "kind": q["kind"], "pair": q.get("pair"),
                        "prompt": q["prompt"][lang], "visual": q["visual"][lang], "text": q["text"][lang],
                        "en_visual": q["visual"]["en"], "en_text": q["text"]["en"],   # to spot TR prompts answered in English
                        "answer_type": answer_type(q), "cue_px": px,
                        "visual_dir": ("up" if q["visual"]["en"][0] in UP["en"] else "down"
                                       if q["visual"]["en"][0] in DOWN["en"] else None),
                        "pair_more_is_yes": more_yes.get(q.get("pair")),
                    })

    (ROOT / "questions.json").write_text(json.dumps(rows, ensure_ascii=False, indent=1), encoding="utf-8")
    with open(ROOT / "questions.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        for r in rows:
            w.writerow({**r, **{k: " | ".join(r[k]) for k in ("visual", "text", "en_visual", "en_text")}})

    write_questions_md(specs)
    images = sorted({r["image"] for r in rows})
    bundle = ROOT / "chart_conflict_bundle.zip"
    with zipfile.ZipFile(bundle, "w", zipfile.ZIP_DEFLATED) as z:
        z.write(ROOT / "questions.json", "questions.json")
        for img in images:
            z.write(IMAGES / img, f"images/{img}")

    nq = sum(len(s["questions"]) for s in specs)
    print(f"{len(specs)} stimuli · {len(images)} images · {nq} questions · {len(rows)} (image, prompt) rows per model")
    print("rows per version:", dict(Counter(r["cond"] for r in rows)))
    print("mechanisms:", dict(Counter(s["mechanism"] for s in specs)))
    print("question kinds:", dict(Counter(q["kind"] for s in specs for q in s["questions"])))
    yn = Counter(q["visual"]["en"][0] for s in specs for q in s["questions"] if q["visual"]["en"][0] in ("yes", "no"))
    print("visual answer of yes/no questions:", dict(yn))
    pm = Counter(v for s in specs for v in pair_more_is_yes(s).values())
    print("pairs where the drawing says yes to the 'more' wording:", pm.get(True, 0), "· no:", pm.get(False, 0),
          "· undetected:", sum(len({q['pair'] for q in s['questions'] if q.get('pair')}) for s in specs) - pm.total())
    dirs = Counter(r["visual_dir"] for r in rows if r["visual_dir"] and r["cond"] == "consistent" and r["lang"] == "en")
    print("trend questions, drawing direction:", dict(dirs))
    print("cue_px:", {s["id"].split("_")[0]: next(r["cue_px"] for r in rows if r["stimulus"] == s["id"]) for s in specs})
    print(f"bundle: {bundle.name} ({bundle.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
